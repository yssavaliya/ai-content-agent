from __future__ import annotations

import json
import smtplib
import ssl
from email.message import EmailMessage
from pathlib import Path

from ..provider import PublishResult, Publisher


class EmailPublisher(Publisher):
    @property
    def name(self) -> str:
        return "email"

    def __init__(
        self,
        smtp_host: str,
        smtp_port: int,
        smtp_user: str,
        smtp_password: str,
        smtp_from: str,
        smtp_to: str,
        use_tls: bool = True,
    ) -> None:
        self.smtp_host = smtp_host
        self.smtp_port = smtp_port
        self.smtp_user = smtp_user
        self.smtp_password = smtp_password
        self.smtp_from = smtp_from
        self.smtp_to = smtp_to
        self.use_tls = use_tls

    def publish(self, package_path: str) -> PublishResult:
        package = json.loads(Path(package_path).read_text(encoding="utf-8"))

        creation = package.get("creation") or {}
        image = package.get("image") or {}
        research = package.get("research") or {}

        caption = creation.get("caption", "")
        hashtags = creation.get("hashtags", [])
        alt_text = creation.get("alt_text", "")
        media_url = image.get("media_url", "")
        topic = research.get("recommended_topic", "")

        subject = f"Instagram Post Ready: {topic[:50]}" if topic else "Instagram Post Ready"

        body = f"""Instagram Post Ready for Manual Publishing

Topic: {topic}

Caption:
{caption}

Hashtags:
{" ".join(hashtags) if hashtags else "(none)"}

Alt Text:
{alt_text if alt_text else "(none)"}

Image URL:
{media_url if media_url else "(no public URL - check local images/ folder)"}

---
Generated by AI Content Agent
Run ID: {package.get("run_id", "unknown")}
"""

        msg = EmailMessage()
        msg["Subject"] = subject
        msg["From"] = self.smtp_from
        msg["To"] = self.smtp_to
        msg.set_content(body)

        context = ssl.create_default_context()

        with smtplib.SMTP(self.smtp_host, self.smtp_port) as server:
            if self.use_tls:
                server.starttls(context=context)
            server.login(self.smtp_user, self.smtp_password)
            server.send_message(msg)

        return PublishResult(
            provider=self.name,
            status="sent",
            published_id=package.get("run_id", "unknown"),
            metadata={
                "smtp_host": self.smtp_host,
                "recipient": self.smtp_to,
                "subject": subject,
            },
        )